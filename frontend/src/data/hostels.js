export function getRecommendations(preferences) {
  const { budget, gender, maxDistance, moveInDate } = preferences;

  let scored = hostels.map(hostel => {
    let score = 0;
    const cheapestRoom = Math.min(...hostel.roomTypes.map(r => r.price));
    const hasAvailability = hostel.roomTypes.some(r => r.available > 0);

    if (gender && gender !== 'all') {
      if (hostel.type === gender || hostel.type === 'unisex') score += 30;
      else return { ...hostel, score: -1 };
    } else {
      score += 10;
    }

    if (budget) {
      if (cheapestRoom <= budget) score += 25;
      if (cheapestRoom <= budget * 0.8) score += 10;
    }

    if (maxDistance) {
      if (hostel.distanceFromNMIMS <= maxDistance) score += 20;
      if (hostel.distanceFromNMIMS <= 1) score += 10;
    }

    score += hostel.rating * 5;
    score += (hostel.residentSatisfaction / 100) * 10;
    if (hasAvailability) score += 15;

    return { ...hostel, score };
  });

  return scored
    .filter(h => h.score > 0)
    .sort((a, b) => b.score - a.score);
}
